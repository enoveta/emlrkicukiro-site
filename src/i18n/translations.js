export function interpolate(str, vars = {}) {
  if (!str) return '';
  return Object.keys(vars).reduce(
    (acc, key) => acc.replace(new RegExp(`\\{${key}\\}`, 'g'), String(vars[key])),
    str
  );
}

/** Pick a localized CMS field: prefers `${field}Rw` when lang = rw, falls back to English. */
export function localized(item, field, lang = 'en') {
  if (!item) return '';
  if (lang === 'rw') {
    const rwValue = item[`${field}Rw`];
    if (rwValue) return rwValue;
  }
  return item[field] ?? '';
}

const MONTHS = {
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
  rw: ['Mutarama', 'Gashyantare', 'Werurwe', 'Mata', 'Gicurasi', 'Kamena', 'Nyakanga', 'Kanama', 'Nzeri', 'Ukwakira', 'Ugushyingo', 'Ukuboza'],
};

const toDate = (value) => {
  const d = value instanceof Date ? value : new Date(value);
  return Number.isNaN(d.getTime()) ? null : d;
};

/** "5 October 2026" / "5 Ukwakira 2026". Dates are stored as UTC days. */
export function formatDate(value, lang = 'en') {
  const d = toDate(value);
  if (!d) return '';
  const months = MONTHS[lang] || MONTHS.en;
  return `${d.getUTCDate()} ${months[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
}

export const formatDay = (value) => {
  const d = toDate(value);
  return d ? String(d.getUTCDate()).padStart(2, '0') : '';
};

export function formatMonthShort(value, lang = 'en') {
  const d = toDate(value);
  if (!d) return '';
  return (MONTHS[lang] || MONTHS.en)[d.getUTCMonth()].slice(0, 3).toUpperCase();
}
